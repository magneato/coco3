            bmi     rl_xd
            pshs    x
            jsr     map_pic
            jsr     xfade
            ldb     #70
            jsr     ticks_b
            puls    x
            bra     rl_xf

            ;; ---- 3. XOR: the mini Mandelbrot XOR the whole set, wiped in and out ----
