            ldb     #40             ; linger in the deep end
            jsr     ticks_b
rl_zo:      dec     <frame
            jsr     zshow
            tst     <frame
            bne     rl_zo
            ldb     #30
            jsr     ticks_b
            dec     <dir
            bne     rl_zp
            jsr     restore_view

            ;; ---- 2. the gallery under one palette, crossfaded through an ordered dither ----
            ldx     #zoom0
            leax    S_PAL,x
            jsr     set_pal         ; (rainbow, cycling: every escape picture wears it)
            clra
            jsr     map_pic
            jsr     fizzle_pic      ; Mandelbrot
