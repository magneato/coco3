            jsr     xwipe
            ldb     #90
            jsr     ticks_b
            jsr     xwipe
            ldb     #30
            jsr     ticks_b

            ;; ---- 4. FizzleFade into the rabbit, lift it off as a texture, spin it ----
            lda     #2
            jsr     map_pic
            ldx     #scene2
            leax    S_PAL,x
            jsr     set_pal
            jsr     fizzle_pic
            ldb     #40
            jsr     ticks_b
            jsr     rotozoom
            jsr     restore_view

