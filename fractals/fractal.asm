            ldx     #zoom0
            leax    S_PAL,x
            jsr     set_pal
            lda     #1
            sta     <cycling
            lda     #2
            sta     <finest         ; 2x2 is enough for a moving picture
            ldx     #zoom0
            stx     <scn
            clr     <frame
rl_zf:      lda     <frame
            lsla
            adda    #ZOOM_PG
            pshs    a
            jsr     map_work
            jsr     clear_screen
            puls    a
            jsr     show_page
