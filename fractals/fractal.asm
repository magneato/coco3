            ldd     <scn
            addd    #E_SIZE
            std     <scn
            inc     <frame
            lda     <frame
            cmpa    #NZOOM
            blo     rl_zf
            ;; ... and play them: in, out, in, out, in, out - one frame per 5 vsyncs, page flips only
            lda     #3
