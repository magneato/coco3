            jsr     munch
            ldb     #60
            jsr     ticks_b

            ;; ---- 6. bitwise textures: x XOR y, x AND y, x OR y, x * y ----
            jsr     bitwise

            ;; ---- the end: fade out, and say so ----
            jsr     fizzle_black
