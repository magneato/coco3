            bne     ticks_b
            rts

;;; ---------------------------------------------------------------------------
;;; FIZZLEFADE.  A 16-bit xorshift visits every value 1-65535 exactly once; read as (row, column) it
;;; touches each of the 160x192 pixels once, in an order that looks random.  Each pixel takes the
;;; colour of the same pixel in the picture in W4/W5, or black.  (Pixel 0 is copied at the end: the
;;; generator never says 0.)
;;; ---------------------------------------------------------------------------
fizzle_black:
            clr     <fz_src
            bra     fizzle
fizzle_pic: lda     #1
            sta     <fz_src
fizzle:     ldd     #1
            std     <seed
            ldd     #$FFFF
            std     <left
fz_l:       jsr     rnd
            ldd     <seed
            cmpa    #192
            bhs     fz_n
            cmpb    #160
            bhs     fz_n
            ldx     #ROWTAB
            pshs    b
            tfr     a,b
            abx
            abx
            ldx     ,x
            puls    b
            lsrb
            abx                     ; (ABX leaves C, the column's low bit, alone)
            bcs     fz_odd
            lda     ,x
            anda    #$0F
            tst     <fz_src
            beq     fz_st
            ldb     $4000,x
            andb    #$F0
            stb     <tt
            ora     <tt
            bra     fz_st
fz_odd:     lda     ,x
            anda    #$F0
            tst     <fz_src
            beq     fz_st
            ldb     $4000,x
            andb    #$0F
            stb     <tt
            ora     <tt
fz_st:      sta     ,x
fz_n:       dec     <poll
            bne     fz_c
            jsr     check_keys
fz_c:       ldd     <left
            subd    #1
            std     <left
            bne     fz_l
            clra                    ; pixel 0 (and its partner, already right)
            tst     <fz_src
            beq     fz_z
            lda     SCREEN+$4000
fz_z:       sta     SCREEN
            rts

;;; ---------------------------------------------------------------------------
;;; ORDERED-DITHER CROSSFADE to the picture in W4/W5: 16 steps; at step t every byte whose 4x4
;;; Bayer threshold is t switches over (one row in four, one byte in four: 960 bytes a step)
;;; ---------------------------------------------------------------------------
xfade:      ldu     #bayer_tab
xd_t:       ldx     #ROWTAB
            ldb     ,u              ; first row: the threshold's row in the 4x4 matrix
            abx
            abx
xd_row:     ldy     ,x
            ldb     1,u
            leay    b,y             ; first byte: its column
            lda     #20
            sta     <cnt
xd_b:       ldb     $4000,y
            stb     ,y
            leay    4,y
            dec     <cnt
            bne     xd_b
            leax    8,x             ; four rows on
            cmpx    #ROWTAB+384
            blo     xd_row
            ldb     #3
            pshs    u
            jsr     ticks_b
            puls    u
            leau    2,u
            cmpu    #bayer_tab+32
            bne     xd_t
            rts

;;; XOR WIPE: the screen ^= the picture in W4/W5, four rows per vsync (do it twice to undo it)
xwipe:      ldx     #SCREEN
xw_r:       lda     #160            ; 4 rows = 160 words
            sta     <cnt
xw_b:       ldd     $4000,x
            eora    ,x
            eorb    1,x
            std     ,x++
            dec     <cnt
            bne     xw_b
            ldb     #1
            jsr     ticks_b
            cmpx    #SCREEN+192*80
            bne     xw_r
            rts

;;; ---------------------------------------------------------------------------
;;; ROTOZOOMER.  The screen (the rabbit) is sampled into a 64x64 texture, 256 bytes per texel row,
;;; so (v, u) -> address is just A = v | $80, B = u.  Then NROT frames: 40x48 blocks of 4x4 pixels,
;;; texture coordinates stepped in 8.8 fixed point, drawn into the hidden buffer and flipped in.
;;; ---------------------------------------------------------------------------
rotozoom:   ldd     #TEX_PG*256+TEX_PG+1
            std     MMU4
            clr     <py             ; texture row v <- picture row 3v
            ldy     #TEXBASE
rz_tv:      clr     <rowc           ; texture column u <- picture column (5u) >> 1
rz_tu:      lda     <rowc
            ldb     #5
            mul
            lsra
            rorb
            tfr     b,a
            ldb     <py
            pshs    y
            jsr     getc
            puls    y
            ldb     #$11
            mul
            stb     ,y+
            inc     <rowc
            lda     <rowc
            cmpa    #64
            blo     rz_tu
            leay    192,y           ; next texel row (256 apart)
            lda     <py
            adda    #3
            sta     <py
            cmpa    #192
            blo     rz_tv
            ;; play
            ldx     #roto_tab
            stx     <rzp
            clr     <frame
rz_f:       lda     <frame
            anda    #1
            beq     rz_b1
            lda     #SCR_PG
            bra     rz_b2
rz_b1:      lda     #BACK_PG
rz_b2:      pshs    a
            jsr     map_work
            jsr     rz_draw
            jsr     tick
            puls    a
            jsr     show_page
            jsr     check_keys
            ldd     <rzp
            addd    #12
            std     <rzp
            inc     <frame
            lda     <frame
            cmpa    #NROT
            blo     rz_f
            rts

rz_draw:    ldx     <rzp
            ldd     ,x
            std     <ur
            ldd     2,x
            std     <vr
            ldd     4,x
            std     <du
            ldd     6,x
            std     <dv
            ldd     8,x
            std     <ru
            ldd     10,x
            std     <rv
            ldy     #SCREEN
            lda     #48
            sta     <rowc
rd_row:     ldd     <ur
            std     <u
            ldd     <vr
            std     <v
            lda     #40
            sta     <cnt
rd_tx:      ldd     <v
            addd    <dv
            std     <v
            anda    #63
            ora     #$80
            sta     <tt
            ldd     <u
            addd    <du
            std     <u
            tfr     a,b
            andb    #63
            lda     <tt
            tfr     d,x
            lda     ,x
            tfr     a,b
            std     ,y
            std     80,y
            std     160,y
            std     240,y
            leay    2,y
            dec     <cnt
            bne     rd_tx
            leay    240,y
            ldd     <ur
            addd    <ru
            std     <ur
            ldd     <vr
            addd    <rv
            std     <vr
            jsr     vpoll
            dec     <rowc
            bne     rd_row
            rts

;;; ---------------------------------------------------------------------------
;;; MUNCHING SQUARES: for t = 0 ... 767, every pixel (x, x XOR t) is XORed with a colour that
;;; depends on t.  Two values of t per vsync.
;;; ---------------------------------------------------------------------------
munch:      ldx     #scene2
            leax    S_PAL,x
            jsr     set_pal
            jsr     clear_screen
            ldd     #0
            std     <mt
mu_t:       ldd     <mt             ; colour = 1 + (t / 16) mod 15
            lsra
            rorb
            lsra
            rorb
            lsra
            rorb
            lsra
            rorb
            ldx     #MOD15
            abx
            lda     ,x
            sta     <colour
            clr     <px
mu_x:       lda     <px
            tfr     a,b
            eorb    <mt+1           ; y = x XOR t
            cmpb    #192
            bhs     mu_n
            ldx     #ROWTAB
            abx
            abx
            ldx     ,x
