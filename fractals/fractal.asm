;;; =============================================================================
;;; FRACTAL.ASM - fixed-point fractals for the TRS-80 CoCo3 (6809E + GIME, 2 MB), a CoCoWolf3D side show
;;; =============================================================================
;;; "Constraints breed elegance, not limitations."
;;;
;;; Nine scenes, then an effects reel, round and round (keys 1-9 jump to a scene, 0 to the reel,
;;; SPACE skips, BREAK returns to BASIC):
;;;   1 Mandelbrot set   2 a mini Mandelbrot on the needle   3 Douady's rabbit (Julia)
;;;   4 Julia c=-0.8+0.156i   5 Burning Ship   6 Tricorn   7 Barnsley fern   8 Heighway dragon
;;;   9 Sierpinski triangle
;;;   0 the reel: a zoom into the needle (20 frames drawn into their own pages, then played back by
;;;     moving the GIME's video offset), dithered crossfades, an XOR blend, Wolfenstein's own
;;;     FizzleFade, a rotozoomer, munching squares and bitwise textures, all under palette cycling
;;; The scene list is generated by scripts/fractal_scenes.py (build/fractal.inc), which also holds a
;;; bit-exact Python model of everything below.
;;;
;;; The glass   : GIME 160x192x16 at phys $60000 (W2/W3), exactly as in wolf3d.asm.
;;; Numbers     : signed 16 bit, 1.0 = 8192, always EVEN (range -4..4, resolution 1/4096).
;;;
;;; =============================================================================

;;; ---------------------------------------------------------------------------
;;; The machine's organs
;;; ---------------------------------------------------------------------------
INIT0       equ     $FF90
INIT1       equ     $FF91
VMODE       equ     $FF98
VRES        equ     $FF99
BORDER      equ     $FF9A
VBANK       equ     $FF9B
VSCROLL     equ     $FF9C
VOFFH       equ     $FF9D
VOFFL       equ     $FF9E
HOFFS       equ     $FF9F
MMU0        equ     $FFA0
MMU2        equ     $FFA2
MMU4        equ     $FFA4
MMU6        equ     $FFA6
PALETTE     equ     $FFB0
PIA0DA      equ     $FF00           ; keyboard rows (a pressed key reads 0)
PIA0DB      equ     $FF02           ; keyboard columns; reading it clears the VSYNC flag
PIA0CRB     equ     $FF03           ; bit 7 = VSYNC flag
FDCCTL      equ     $FF40
FDCCMD      equ     $FF48
SLOW        equ     $FFD8
FAST        equ     $FFD9
ROMMODE     equ     $FFDE
RAMMODE     equ     $FFDF
RESETVEC    equ     $FFFE
VRES_160    equ     %00010110       ; 192 lines, 160 px (80 B/row), 16 colours

;;; ---------------------------------------------------------------------------
;;; Memory: W0 = direct page, ledgers, stack; W1 = this code; W2/W3 = the screen; W4-W6 = squares
;;; ---------------------------------------------------------------------------
STACK       equ     $1FF0
SCREEN      equ     $4000
SCR_PG      equ     $30
SQBASE      equ     $8000           ; squares ledger: the entry for v sits at SQBASE + |v|
SQ_PG       equ     $32             ; pages $32-$34
SQEND       equ     $E000           ; covers |v| < 3.0
TEXTSCR     equ     $0400           ; BASIC's 32x16 text screen: the title
ROWTAB      equ     $0A00           ; 192 x 2: address of each screen row
CXTAB       equ     $0C00           ; 160 x 2: real part of each column
CYTAB       equ     $0E00           ; 192 x 2: imaginary part of each row
SWAPTAB     equ     $1080           ; 256: nibble-swapped bytes, indexed by a SIGNED byte around $1080
MOD15       equ     $1100           ; 256: colour of an escape after n iterations, 1 + n mod 15
SHOW_TICKS  equ     300             ; a finished picture stays 5 s
PIC_PG      equ     $40             ; finished pictures: scene n in pages $40+2n, $41+2n
ZOOM_PG     equ     $00             ; zoom frame k in pages 2k, 2k+1 (inside the first 512 KB: displayable)
BACK_PG     equ     $28             ; the rotozoomer's second buffer
TEX_PG      equ     $52             ; rotozoomer texture: 64 rows of 64 texels, 256 bytes apart (16 KB)
TEXBASE     equ     $8000
CYCLE_RATE  equ     4               ; palette cycling: one step every 4 vsyncs
COUNT       equ     6               ; IFS: transient points that are not plotted

;;; scene record (build/fractal.inc)
S_KIND      equ     0               ; 0 = escape time, 1 = iterated function system
S_CYCLE     equ     1               ; 1 = cycle colours 1-15 once drawn
S_PAL       equ     2               ; 16 GIME palette bytes
E_FORM      equ     18              ; 0 Mandelbrot, 1 Julia, 2 Burning Ship, 3 Tricorn
E_ITER      equ     19              ; iteration limit
E_MIRROR    equ     20              ; 0 none, 1 top/bottom, 2 point symmetry
E_X0        equ     22              ; real part of column 0
E_DX        equ     24              ; ... step per column
E_Y0        equ     26              ; imaginary part of row 0
E_DY        equ     28              ; ... step per row (subtracted)
E_JX        equ     30              ; Julia constant
E_JY        equ     32
E_SIZE      equ     34
I_MODE      equ     18              ; 0 = colour counts hits (density), 1 = colour of the map
I_NMAPS     equ     19
I_NPTS      equ     20              ; points to plot
I_OX        equ     22              ; screen position of the origin
I_OY        equ     24
I_SX        equ     26              ; pixel scale: offset = (coordinate * scale) >> 6
I_SY        equ     28
I_MAPS      equ     30
M_THR       equ     0               ; the map is taken when the random byte is <= this
M_COL       equ     1
M_A         equ     2               ; x' = a x + b y + e,  y' = c x + d y + f
M_B         equ     4
M_C         equ     6
M_D         equ     8
M_E         equ     10
M_F         equ     12
MAPSZ       equ     14

NEGD        macro
            nega
            negb
            sbca    #0
            endm

;;; ---------------------------------------------------------------------------
;;; Direct page.  $06 and $0B follow wolf3d.asm: run.sh's autoboot drops to real time once the word
;;; at $06 counts and the byte at $0B is below $80.
;;; ---------------------------------------------------------------------------
            setdp   $00
            org     $0000
zx          rmb     2               ; $00  z, real part
zy          rmb     2               ; $02  z, imaginary part
x2          rmb     2               ; $04  zx^2
ticks       rmb     2               ; $06  vsyncs seen (starts at 1)
y2          rmb     2               ; $08  zy^2
cnt         rmb     1               ; $0A  iterations left
quiet       rmb     1               ; $0B  always 0
laps        rmb     1               ; $0C  effects reels completed (run.sh --whole stops recording on it)
r2          rmb     2               ; zx^2 + zy^2
ax          rmb     2               ; |zx| (Burning Ship)
ay          rmb     2               ; |zy|
tt          rmb     2               ; scratch
cre         rmb     2               ; c, real part
cim         rmb     2               ; c, imaginary part
maxit       rmb     1               ; iteration limit of this scene
julia       rmb     1               ; nonzero: c is the scene's constant, z starts at the pixel
iter_fn     rmb     2               ; -> the iteration loop of this scene's formula
scn         rmb     2               ; -> the scene record
abort_sp    rmb     2               ; stack pointer to return through when a key interrupts a render
scene       rmb     1               ; scene number, 0-based
px          rmb     1               ; pixel being worked on
py          rmb     1
step        rmb     1               ; block size of this pass: 4, 2 or 1
rows        rmb     1               ; rows computed: 192, or 96 when the rest is mirrored
colour      rmb     1
timer       rmb     2               ; showcase: vsyncs left
cyc         rmb     1               ; vsyncs to the next palette step
seed        rmb     2               ; xorshift state
ix          rmb     2               ; IFS point
iy          rmb     2
nx          rmb     2
acc         rmb     2
map         rmb     2               ; -> the map chosen for this point
left        rmb     2               ; points still to make
skip        rmb     1               ; transient points still to skip
poll        rmb     1               ; points until the next keyboard poll
ma          rmb     2               ; fmul operands
mb          rmb     2
sqp         rmb     2
pal         rmb     16              ; the palette as shown (cycled)
cycling     rmb     1               ; nonzero: colours 1-15 rotate on every CYCLE_RATE-th vsync
finest      rmb     1               ; render_escape stops after the pass of this block size (1 or 2)
fz_src      rmb     1               ; fizzle: 0 = to black, else from the picture in W4/W5
frame       rmb     1               ; reel: frame counter
dir         rmb     1               ; reel: playback direction / round
rowc        rmb     1
u           rmb     2               ; rotozoomer: texture coordinates (8.8)
v           rmb     2
ur          rmb     2               ; ... at the start of the block row
vr          rmb     2
du          rmb     2               ; ... step per block across
dv          rmb     2
ru          rmb     2               ; ... step per block down
rv          rmb     2
rzp         rmb     2               ; -> this frame's rotozoomer record
mt          rmb     2               ; munching squares: t
op          rmb     1               ; bitwise texture: which operator
blank       rmb     1               ; nonzero: the screen is already black (no fizzle needed)
sacc        rmb     4               ; squares ledger forge: 16 k^2 + $8000
dacc        rmb     4               ; ... and its next increment 16 (2k + 1)

;;; ===========================================================================
            org     $2000
start:
            orcc    #$50
            clra
            tfr     a,dp
            lds     #STACK
            sta     SLOW
            lda     #$D0
            sta     FDCCMD          ; floppy: force interrupt, motor off, no NMI
            clr     FDCCTL
            ldd     #nmi_rti
            std     $FEFC           ; NMI vector (constant vector page) -> a bare RTI
            sta     RAMMODE         ; all-RAM map; INIT0 stays $CC for now: BASIC's text screen stays up
            ldd     #SCR_PG*256+SCR_PG+1
            std     MMU2            ; W2/W3: the screen
            jsr     map_squares     ; W4-W6: squares
            lda     #SQ_PG+2
            sta     MMU6
            sta     FAST
            ldx     #0
st_dp:      clr     ,x+
            cmpx    #$100
            bne     st_dp
            ldd     #1
            std     <ticks          ; we are running (run.sh watches this)

            ;; the title, on the natives' own green text screen, while the ledgers are forged
            ldx     #TEXTSCR
            lda     #$60            ; (a VDG space)
st_cls:     sta     ,x+
            cmpx    #TEXTSCR+512
            bne     st_cls
            ldx     #title_txt
            ldu     #TEXTSCR
st_ln:      tst     ,x
            beq     st_forge
            ldb     #32
st_ch:      lda     ,x+
            sta     ,u+
            decb
            bne     st_ch
            bra     st_ln
st_forge:   jsr     forge_squares
            jsr     forge_ledgers
            ldd     #$5245          ; 'RE'..
            std     TEXTSCR+32*12+2
            ldd     #$4144          ; 'AD'
            std     TEXTSCR+32*12+4
            ldd     #$596E          ; 'Y.'
            std     TEXTSCR+32*12+6
            ldx     #150            ; let it be read
st_wait:    jsr     wait_vsync
            leax    -1,x
            bne     st_wait

            ldx     #pal            ; black while the graphics screen is prepared
            ldb     #16
st_blk:     clr     ,x+
            decb
            bne     st_blk
            jsr     show_pal
            jsr     clear_screen
            lda     #$4C            ; GIME: CoCo3 mode, MMU on, constant vectors
            sta     INIT0
            clr     INIT1
            lda     #$80            ; 160x192x16
            sta     VMODE
            lda     #VRES_160
            sta     VRES
            clr     VBANK
            clr     VSCROLL
            clr     HOFFS
            clr     BORDER
            lda     #SCR_PG
            jsr     show_page
            inc     <blank

main:       lda     <scene
            cmpa    #NSCENES
            beq     mn_reel
            jsr     run_scene       ; A = what ended it: 0 time, 1-9 digit, 10 zero, $80 SPACE, $FF BREAK
            bra     mn_key
mn_reel:    jsr     wait_release
            ldx     #reel
            jsr     guard
            pshs    a
            jsr     restore_view
            puls    a
mn_key:     cmpa    #$FF
            beq     do_exit
            tsta
            bmi     mn_next
            beq     mn_next
            deca                    ; 1-9 -> scene 0-8, 0 (code 10) -> 9 = the reel
            sta     <scene
            bra     main
mn_next:    lda     <scene
            inca
            cmpa    #NSCENES
            bls     mn_set
            clra
mn_set:     sta     <scene
            bra     main

;;; ---------------------------------------------------------------------------
;;; EXIT - stock page map and video, then BASIC's cold start (as wolf3d.asm)
;;; ---------------------------------------------------------------------------
do_exit:
            orcc    #$50
            sta     SLOW
            ldx     #MMU0
            lda     #$38
dx_mm:      sta     ,x+
            inca
            cmpa    #$40
            bne     dx_mm
            clr     INIT1
            clr     VMODE
            clr     VRES
            clr     VOFFH
            clr     VOFFL
            clr     BORDER
            lda     #$CC            ; CoCo-compatible video, MMU on (BASIC's setting)
            sta     INIT0
            clr     $71             ; invalidate BASIC's warm-start flag: cold start
            sta     ROMMODE
            jmp     [RESETVEC]
nmi_rti:    rti

;;; ---------------------------------------------------------------------------
;;; FORGE THE SQUARES LEDGER: entry(v = 2k) = 2 round(k^2 / 4096), i.e. v^2 in our units, even.
;;; k^2 grows by odd numbers: S = 16 k^2 + $8000 (rounding) gains 16 (2k + 1) per step, so the entry
;;; is twice the high word of S.  Entries past $FFFE (|v| > 2.83) saturate.
;;; ---------------------------------------------------------------------------
forge_squares:
            ldx     #SQBASE
            ldd     #$8000
            std     <sacc+2
            ldd     #16
            std     <dacc+2
fs_l:       ldd     <sacc
            cmpd    #$8000
            blo     fs_ok
            ldd     #$7FFF
fs_ok:      aslb
            rola
            std     ,x++
            ldd     <sacc+2         ; S += delta (32 bit)
            addd    <dacc+2
            std     <sacc+2
            ldd     <sacc
            adcb    <dacc+1
            adca    <dacc
            std     <sacc
            ldd     <dacc+2         ; delta += 32
            addd    #32
            std     <dacc+2
            ldd     <dacc
            adcb    #0
            adca    #0
            std     <dacc
            cmpx    #SQEND
            blo     fs_l
            rts

;;; ---------------------------------------------------------------------------
;;; the small ledgers: row addresses, nibble swaps, colour bands
;;; ---------------------------------------------------------------------------
forge_ledgers:
            ldx     #ROWTAB
            ldd     #SCREEN
fl_row:     std     ,x++
            addd    #80
            cmpx    #ROWTAB+384
            bne     fl_row
            ldy     #SWAPTAB        ; swap(b) at SWAPTAB + (signed) b
            clrb
fl_sw:      tfr     b,a
            lsla
            lsla
            lsla
            lsla
            sta     <tt
            tfr     b,a
            lsra
            lsra
            lsra
            lsra
            ora     <tt
            sta     b,y
            incb
            bne     fl_sw
            ldx     #MOD15
            lda     #1
fl_md:      sta     ,x+
            inca
            cmpa    #16
            bne     fl_mn
            lda     #1
fl_mn:      cmpx    #MOD15+256
            bne     fl_md
            rts

;;; ---------------------------------------------------------------------------
;;; ONE SCENE: fizzle the old picture away, palette, draw, park the picture, show off.
;;; Returns A = key (0 = time ran out).
;;; ---------------------------------------------------------------------------
run_scene:
            ldx     #scene_tab
            ldb     <scene
            aslb
            ldx     b,x
            stx     <scn
            jsr     wait_release
            clr     <cycling
            tst     <blank
            bne     rs_blank
            ldx     #fizzle_black
            jsr     guard
            tsta
            bne     rs_out
rs_blank:   clr     <blank
            jsr     black_pal
            ldx     <scn
            leax    S_PAL,x
            jsr     set_pal
            lda     #1
            sta     <finest
            ldx     <scn
            tst     S_KIND,x
            bne     rs_ifs
            ldx     #render_escape
            bra     rs_go
rs_ifs:     ldx     #render_ifs
rs_go:      jsr     guard
            tsta
            bne     rs_out
            jsr     save_pic
            jsr     showcase
rs_out:     rts

;;; guard: run the routine at X; a key pressed inside it (check_keys) returns here at once, A = key
guard:      sts     <abort_sp
            jsr     ,x
            clra
            rts

;;; the finished picture: palette cycling (escape scenes) for SHOW_TICKS vsyncs, or until a key
showcase:
            ldx     <scn
            lda     S_CYCLE,x
            sta     <cycling
            ldd     #SHOW_TICKS
            std     <timer
sc_l:       jsr     tick
            jsr     scan_keys
            bne     sc_out
            ldd     <timer
            subd    #1
            std     <timer
            bne     sc_l
            clra
sc_out:     rts

;;; tick: wait for the next vsync, count it, cycle the palette when it is time
tick:       lda     PIA0DB          ; clear the flag, then wait for the next field
tk_l:       lda     PIA0CRB
            bpl     tk_l
            bra     on_vsync
;;; vpoll: the same, but only if a vsync has happened (long loops call it now and then)
vpoll:      lda     PIA0CRB
            bmi     vp_yes
            rts
vp_yes:     lda     PIA0DB
on_vsync:   ldd     <ticks
            addd    #1
            std     <ticks
            tst     <cycling
            beq     ov_out
            dec     <cyc
            bpl     ov_out
            lda     #CYCLE_RATE-1
            sta     <cyc
            pshs    x,y
            ldx     #pal+1          ; colours 1-15 move one place down the bands
            lda     ,x
            ldy     #14
ov_rot:     ldb     1,x
            stb     ,x+
            leay    -1,y
            bne     ov_rot
            sta     ,x
            jsr     show_pal
            puls    x,y
ov_out:     rts

wait_vsync  equ     tick

black_pal:  ldx     #pal
            ldb     #16
bp_l:       clr     ,x+
            decb
            bne     bp_l
            jsr     tick
            bra     show_pal
;;; set_pal: X -> 16 palette bytes, shown at the next vsync
set_pal:    ldy     #pal
            ldb     #16
stp_l:      lda     ,x+
            sta     ,y+
            decb
            bne     stp_l
            jsr     tick
show_pal:   pshs    x,y
            ldx     #pal
            ldy     #PALETTE
            ldb     #16
sp_l:       lda     ,x+
            sta     ,y+
            decb
            bne     sp_l
            puls    x,y,pc

clear_screen:
            ldx     #SCREEN
            ldd     #0
cs_l:       std     ,x++
            std     ,x++
            std     ,x++
            std     ,x++
            cmpx    #SCREEN+192*80
            bne     cs_l
            rts

;;; ---------------------------------------------------------------------------
;;; the 2 MB, through the windows
;;; ---------------------------------------------------------------------------
map_squares:
            ldd     #SQ_PG*256+SQ_PG+1
            std     MMU4
            rts
;;; map_pic: A = scene -> its parked picture in W4/W5 ($8000, i.e. the screen address + $4000)
map_pic:    lsla
            adda    #PIC_PG
            tfr     a,b
            incb
            std     MMU4
            rts
;;; map_work: A = page -> W2/W3 (what the drawing routines draw on)
map_work:   tfr     a,b
            incb
            std     MMU2
            rts
;;; show_page: A = page (below $40) -> the GIME shows phys A * 8 KB
show_page:  lsla
            lsla
            sta     VOFFH
            clr     VOFFL
            rts
restore_view:
            lda     #SCR_PG
            jsr     map_work
            lda     #SCR_PG
            jsr     show_page
            bra     map_squares

;;; save_pic: the screen -> this scene's pages
save_pic:   lda     <scene
            jsr     map_pic
            ldx     #SCREEN
sv_l:       ldd     ,x
            std     $4000,x
            ldd     2,x
            std     $4002,x
            leax    4,x
            cmpx    #SCREEN+192*80
            bne     sv_l
            bra     map_squares

;;; ---------------------------------------------------------------------------
;;; KEYS: A = 1-9 digit, 10 zero, $80 SPACE, $FF BREAK, 0 none (flags set from A)
;;; ---------------------------------------------------------------------------
scan_keys:
            sta     SLOW
            ldx     #keytab
sk_l:       lda     ,x
            beq     sk_out          ; (A = 0: nothing pressed)
            sta     PIA0DB
            lda     PIA0DA
            coma
            anda    1,x
            bne     sk_hit
            leax    3,x
            bra     sk_l
sk_hit:     lda     2,x
sk_out:     ldb     #$FF
            stb     PIA0DB
            sta     FAST
            tsta
            rts
;;;               column strobe, row bit, code
keytab:     fcb     $FD,$10,1,$FB,$10,2,$F7,$10,3,$EF,$10,4,$DF,$10,5,$BF,$10,6,$7F,$10,7
            fcb     $FE,$20,8,$FD,$20,9,$FE,$10,10,$7F,$08,$80,$FB,$40,$FF,0

wait_release:
            jsr     tick
            jsr     scan_keys
            bne     wait_release
            rts

;;; while drawing: let the palette move, and a key abandons the work (back to the guard, A = key)
check_keys:
            pshs    x
            jsr     vpoll
            jsr     scan_keys
            puls    x
            bne     ck_quit
            rts
ck_quit:    lds     <abort_sp
            rts

;;; ===========================================================================
;;; ESCAPE-TIME FRACTALS
;;; ===========================================================================
render_escape:
            ldx     <scn
            lda     E_ITER,x
            sta     <maxit
            ldb     #192
            tst     E_MIRROR,x
            beq     re_h
            ldb     #96
re_h:       stb     <rows
            lda     E_FORM,x
            cmpa    #1
            bne     re_nj
            sta     <julia          ; 1 = Julia
            clra
            bra     re_fn
re_nj:      clr     <julia
re_fn:      ldy     #formulae
            lsla
            ldd     a,y
            std     <iter_fn
            ldd     E_X0,x          ; the real part of every column ...
            ldy     #CXTAB
re_cx:      std     ,y++
            addd    E_DX,x
            cmpy    #CXTAB+320
            bne     re_cx
            ldd     E_Y0,x          ; ... and the imaginary part of every row
            ldy     #CYTAB
re_cy:      std     ,y++
            subd    E_DY,x
            cmpy    #CYTAB+384
            bne     re_cy

            ;; pass 1: every 4th pixel of every 4th row, drawn as a 4x4 block
            lda     #4
            sta     <step
            clr     <py
p1_row:     clr     <px
p1_px:      jsr     calc
            jsr     fill
            lda     <px
            adda    #4
            sta     <px
            cmpa    #160
            blo     p1_px
            jsr     check_keys
            lda     <py
            adda    #4
            sta     <py
            cmpa    <rows
            blo     p1_row
            jsr     mirror
            ;; passes 2 and 3: fill in the grid at 2x2, then 1x1, guessing where the coarse grid agrees
            lda     #2
            sta     <step
            jsr     refine
            jsr     mirror
            lda     <finest
            cmpa    #2
            beq     re_done
            lda     #1
            sta     <step
            jsr     refine
            jsr     mirror
re_done:    clra
            rts

formulae:   fdb     it_mandel,it_mandel,it_ship,it_tricorn

;;; refine: every pixel on the grid of <step> not already on the grid of 2 x <step>.  Its parents are
;;; the coarse-grid pixels around it (left/right, above/below or the four diagonals): when they all
;;; have the same colour, so does it.  At the right and bottom edges it is always computed.
refine:     clr     <py
rf_row:     lda     <py
            bita    <step
            bne     rf_odd
            lda     <step           ; a row of the coarse grid: x = s, 3s, 5s ... between left/right parents
            sta     <px
rf_h:       adda    <step
            cmpa    #160
            bhs     rf_hc
            ldb     <py
            jsr     getc
            sta     <colour
            lda     <px
            suba    <step
            ldb     <py
            jsr     getc
            cmpa    <colour
            beq     rf_hf
rf_hc:      jsr     calc
rf_hf:      jsr     fill
            lda     <px
            adda    <step
            adda    <step
            sta     <px
            cmpa    #160
            blo     rf_h
            bra     rf_next
rf_odd:     clr     <px             ; a row between coarse rows: every x
rf_o:       lda     <px
            bita    <step
            bne     rf_d
            ldb     <py             ; on a coarse column: above/below parents
            addb    <step
            cmpb    <rows
            bhs     rf_oc
            lda     <px
            jsr     getc
            sta     <colour
            lda     <px
            ldb     <py
            subb    <step
            jsr     getc
            cmpa    <colour
            beq     rf_of
            bra     rf_oc
rf_d:       adda    <step           ; between coarse columns: the four diagonal parents
            cmpa    #160
            bhs     rf_oc
            ldb     <py
            addb    <step
            cmpb    <rows
            bhs     rf_oc
            jsr     getc            ; (x+s, y+s)
            sta     <colour
            lda     <px
            suba    <step
            ldb     <py
            addb    <step
            jsr     getc            ; (x-s, y+s)
            cmpa    <colour
            bne     rf_oc
            lda     <px
            adda    <step
            ldb     <py
            subb    <step
            jsr     getc            ; (x+s, y-s)
            cmpa    <colour
            bne     rf_oc
            lda     <px
            suba    <step
            ldb     <py
            subb    <step
            jsr     getc            ; (x-s, y-s)
            cmpa    <colour
            beq     rf_of
rf_oc:      jsr     calc
rf_of:      jsr     fill
            lda     <px
            adda    <step
            sta     <px
            cmpa    #160
            blo     rf_o
rf_next:    jsr     check_keys
            lda     <py
            adda    <step
            sta     <py
            cmpa    <rows
            lblo    rf_row
            rts

;;; getc: A = x, B = y -> A = colour of that pixel (X, B clobbered)
getc:       ldx     #ROWTAB
            abx
            abx
            ldx     ,x
            lsra                    ; C = x is odd (LDB leaves C alone)
            ldb     a,x
            bcs     gc_odd
            lsrb
            lsrb
            lsrb
            lsrb
            tfr     b,a
            rts
gc_odd:     andb    #$0F
            tfr     b,a
            rts

;;; fill: a <step> x <step> block at (px, py) in colour A
fill:       sta     <colour
            ldx     #ROWTAB
            ldb     <py
            abx
            abx
            ldx     ,x
            ldb     <px
            lsrb
            abx
            lda     <colour
            ldb     #$11
            mul                     ; B = the colour in both nibbles
            lda     <step
            cmpa    #2
            blo     fl_1
            beq     fl_2
            tfr     b,a             ; 4 x 4: two bytes on four rows
            std     ,x
            std     80,x
            std     160,x
            std     240,x
            rts
fl_2:       stb     ,x              ; 2 x 2
            stb     80,x
            rts
fl_1:       lda     <px
            lsra
            bcs     fl_odd
            lda     ,x
            anda    #$0F
            sta     ,x
            lda     <colour
            lsla
            lsla
            lsla
            lsla
            ora     ,x
            sta     ,x
            rts
fl_odd:     lda     ,x
            anda    #$F0
            ora     <colour
            sta     ,x
            rts

;;; mirror the computed top half into the bottom half (rows r -> 191 - r)
mirror:     ldx     <scn
            lda     E_MIRROR,x
            beq     mi_none
            cmpa    #1
            beq     mi_rows
            ldx     #SCREEN         ; point symmetry: the row also runs backwards, nibbles swapped
            ldu     #SCREEN+192*80
            ldy     #SWAPTAB
mp_row:     lda     #80
            sta     <cnt
mp_b:       ldb     ,x+
            lda     b,y
            sta     ,-u
            dec     <cnt
            bne     mp_b
            cmpx    #SCREEN+96*80
            bne     mp_row
            rts
mi_rows:    ldx     #SCREEN
            ldu     #SCREEN+191*80
mr_row:     ldb     #40
mr_b:       ldy     ,x++
            sty     ,u++
            decb
            bne     mr_b
            leau    -160,u
            cmpx    #SCREEN+96*80
            bne     mr_row
mi_none:    rts

;;; calc: A = colour of pixel (px, py): 0 inside, else 1 + (iterations mod 15)
calc:       ldx     #CXTAB
            ldb     <px
            abx
            abx
            ldd     ,x
            std     <zx
            std     <cre
            ldx     #CYTAB
            ldb     <py
            abx
            abx
            ldd     ,x
            std     <zy
            std     <cim
            tst     <julia
            beq     ca_go
            ldx     <scn
            ldd     E_JX,x
            std     <cre
            ldd     E_JY,x
            std     <cim
ca_go:      lda     <maxit
            sta     <cnt
            ldu     #SQBASE
            jmp     [iter_fn]

it_escape:  lda     <maxit          ; n = iterations completed
            suba    <cnt
            ldx     #MOD15
            tfr     a,b
            abx
            lda     ,x
            rts

;;; z <- z^2 + c   (Mandelbrot from z = c, Julia from z = pixel): ~165 cycles per iteration
it_mandel:
im_l:       ldd     <zx
            bpl     im_1
            NEGD
im_1:       cmpa    #$40            ; |zx| >= 2: gone
            bhs     it_escape
            ldd     d,u             ; zx^2
            std     <x2
            ldd     <zy
            bpl     im_2
            NEGD
im_2:       cmpa    #$40
            bhs     it_escape
            ldd     d,u             ; zy^2
            std     <y2
            addd    <x2
            bmi     it_escape       ; zx^2 + zy^2 >= 4.0
            std     <r2
            ldd     <zx
            addd    <zy
            bpl     im_3
            NEGD
im_3:       ldd     d,u             ; (zx + zy)^2
            subd    <r2             ; = 2 zx zy
            addd    <cim
            bvs     it_escape
            std     <zy
            ldd     <x2
            subd    <y2
            addd    <cre
            bvs     it_escape
            std     <zx
            dec     <cnt
            bne     im_l
            clra                    ; never escaped: inside
            rts

;;; Burning Ship: z <- (|zx| + i|zy|)^2 + c, so 2|zx zy| = (|zx| + |zy|)^2 - zx^2 - zy^2
it_ship:
is_l:       ldd     <zx
            bpl     is_1
            NEGD
is_1:       cmpa    #$40
            bhs     is_esc
            std     <ax
            ldd     d,u
            std     <x2
            ldd     <zy
            bpl     is_2
            NEGD
is_2:       cmpa    #$40
            bhs     is_esc
            std     <ay
            ldd     d,u
            std     <y2
            addd    <x2
            bmi     is_esc
            std     <r2
            ldd     <ax
            addd    <ay
            ldd     d,u
            subd    <r2
            addd    <cim
            bvs     is_esc
            std     <zy
            ldd     <x2
            subd    <y2
            addd    <cre
            bvs     is_esc
            std     <zx
            dec     <cnt
            bne     is_l
            clra
            rts
is_esc:     jmp     it_escape

;;; Tricorn: z <- conj(z)^2 + c, so the imaginary part is -2 zx zy = zx^2 + zy^2 - (zx + zy)^2
it_tricorn:
it_l:       ldd     <zx
            bpl     it_1
            NEGD
it_1:       cmpa    #$40
            bhs     it_esc
            ldd     d,u
            std     <x2
            ldd     <zy
            bpl     it_2
            NEGD
it_2:       cmpa    #$40
            bhs     it_esc
            ldd     d,u
            std     <y2
            addd    <x2
            bmi     it_esc
            std     <r2
            ldd     <zx
            addd    <zy
            bpl     it_3
            NEGD
it_3:       ldd     d,u
            std     <tt
            ldd     <r2
            subd    <tt
            addd    <cim
            bvs     it_esc
            std     <zy
            ldd     <x2
            subd    <y2
            addd    <cre
            bvs     it_esc
            std     <zx
            dec     <cnt
            bne     it_l
            clra
            rts
it_esc:     jmp     it_escape

;;; ===========================================================================
;;; ITERATED FUNCTION SYSTEMS (the chaos game): pick a map at random, move the point, plot it
;;; ===========================================================================
render_ifs:
            ldd     #1
            std     <seed
            clra
            clrb
            std     <ix
            std     <iy
            ldx     <scn
            ldd     I_NPTS,x
            addd    #COUNT
            std     <left
            lda     #COUNT
            sta     <skip
            lda     #1
            sta     <step
            clr     <poll
            ldu     #SQBASE
ri_l:       jsr     rnd
            ldx     <scn
            leay    I_MAPS,x
ri_m:       cmpa    M_THR,y
            bls     ri_got
            leay    MAPSZ,y
            bra     ri_m
ri_got:     sty     <map
            ldd     <ix             ; x' = a x + b y + e
            std     <ma
            ldd     M_A,y
            std     <mb
            jsr     fmul
            std     <acc
            ldd     <iy
            std     <ma
            ldd     M_B,y
            std     <mb
            jsr     fmul
            addd    <acc
            addd    M_E,y
            std     <nx
            ldd     <ix             ; y' = c x + d y + f
            std     <ma
            ldd     M_C,y
            std     <mb
            jsr     fmul
            std     <acc
            ldd     <iy
            std     <ma
            ldd     M_D,y
            std     <mb
            jsr     fmul
            addd    <acc
            addd    M_F,y
            std     <iy
            ldd     <nx
            std     <ix
            tst     <skip
            beq     ri_plot
            dec     <skip
            bra     ri_next
ri_plot:    ldx     <scn            ; px = ox + (x sx >> 6)
            ldd     <ix
            std     <ma
            ldd     I_SX,x
            std     <mb
            jsr     fmul
            aslb
            rola
            aslb
            rola                    ; A = bits 13-6: the signed pixel offset
            tfr     a,b
            sex
            addd    I_OX,x
            cmpd    #160
            bhs     ri_next
            stb     <px
            ldd     <iy             ; py = oy - (y sy >> 6)
            std     <ma
            ldd     I_SY,x
            std     <mb
            jsr     fmul
            aslb
            rola
            aslb
            rola
            tfr     a,b
            sex
            std     <tt
            ldd     I_OY,x
            subd    <tt
            cmpd    #192
            bhs     ri_next
            stb     <py
            tst     I_MODE,x
            beq     ri_dens
            ldy     <map
            lda     M_COL,y
            bra     ri_put
ri_dens:    lda     <px             ; density: one shade brighter per hit
            ldb     <py
            jsr     getc
            cmpa    #15
            beq     ri_next
            inca
ri_put:     jsr     fill
ri_next:    dec     <poll
            bne     ri_cnt
            jsr     check_keys
ri_cnt:     ldd     <left
            subd    #1
            std     <left
            lbne    ri_l
            clra
            rts

;;; fmul: D = ma * mb = ((ma + mb)^2 - (ma - mb)^2) / 4, kept even.  The difference of the squares
;;; needs 17 bits: the borrow of SUBD is its sign, rotated back in by the first shift.
fmul:       ldd     <ma
            addd    <mb
            bpl     fm_1
            NEGD
fm_1:       ldd     d,u
            std     <sqp
            ldd     <ma
            subd    <mb
            bpl     fm_2
            NEGD
fm_2:       ldd     d,u
            std     <tt
            ldd     <sqp
            subd    <tt
            rora
            rorb
            asra
            rorb
            andb    #$FE
            rts

;;; rnd: xorshift16 (7, 9, 8) -> A = the high byte
rnd:        ldd     <seed           ; v ^= v << 7
            lsra
            rorb                    ; B = low byte of v >> 1, C = bit 0 of v
            eorb    <seed
            stb     <seed
            ldb     #0              ; (LDB keeps C)
            rorb
            eorb    <seed+1
            stb     <seed+1
            lda     <seed           ; v ^= v >> 9
            lsra
            eora    <seed+1
            sta     <seed+1
            eora    <seed           ; v ^= v << 8
            sta     <seed
            rts

