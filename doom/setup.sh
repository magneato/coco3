#!/bin/bash
# ==============================================================================
# setup.sh - CoCo3 DOOM (Freedoom) development environment (Ubuntu 24.04)
# ==============================================================================
# Installs / checks:
#   lwtools   6809 cross-assembler (lwasm).  Built into ./tools if not already installed;
#             an lwtools-4.23.tar.gz in ./tools is used if present (no download needed).
#   mame      the emulator (machine "coco3", needs the coco3 + disk11 ROMs in ~/mame/roms)
#   python3 + numpy + Pillow   used by scripts/ (WAD reading, palette search, tables)
#   freedoom  the Freedoom source checkout in ./freedoom (cloned if missing): all game data comes from it
# ==============================================================================
set -e
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOLS_DIR="${SCRIPT_DIR}/tools"
LWTOOLS_VERSION="4.23"

echo "== CoCo3 DOOM - environment setup =="

echo "-- system packages (build tools, mame, python)"
if command -v apt-get &> /dev/null; then
    sudo apt-get update
    sudo apt-get install -y build-essential git wget curl mame python3 python3-numpy python3-pil \
        || echo "   some packages failed - continuing"
else
    echo "   apt-get not found: install build-essential, git, mame, python3, python3-numpy, python3-pil yourself"
fi

echo "-- lwasm"
LWASM_PATH=""
if command -v lwasm &> /dev/null; then
    LWASM_PATH="$(command -v lwasm)"
elif [ -x "${TOOLS_DIR}/lwtools-${LWTOOLS_VERSION}/lwasm/lwasm" ]; then
    LWASM_PATH="${TOOLS_DIR}/lwtools-${LWTOOLS_VERSION}/lwasm/lwasm"
else
    mkdir -p "${TOOLS_DIR}"
    cd "${TOOLS_DIR}"
    if [ ! -f "lwtools-${LWTOOLS_VERSION}.tar.gz" ]; then
        wget -q "http://www.lwtools.ca/releases/lwtools/lwtools-${LWTOOLS_VERSION}.tar.gz" \
          || wget -q "https://github.com/lwtools/lwtools/archive/refs/tags/v${LWTOOLS_VERSION}.tar.gz" -O "lwtools-${LWTOOLS_VERSION}.tar.gz" \
          || { echo "could not download lwtools; place lwtools-${LWTOOLS_VERSION}.tar.gz in ${TOOLS_DIR} and re-run"; exit 1; }
    fi
    tar xzf "lwtools-${LWTOOLS_VERSION}.tar.gz"
    (cd "lwtools-${LWTOOLS_VERSION}" && make -j"$(nproc)")
    LWASM_PATH="${TOOLS_DIR}/lwtools-${LWTOOLS_VERSION}/lwasm/lwasm"
    cd "${SCRIPT_DIR}"
fi
echo "   lwasm: ${LWASM_PATH}"

echo "-- MAME ROMs"
if [ -f "${HOME}/mame/roms/coco3.zip" ] || [ -f "/usr/share/games/mame/roms/coco3.zip" ]; then echo "   found coco3.zip"
else echo "   MISSING coco3.zip - put the coco3 ROM set (coco3.rom, disk11.rom) in ~/mame/roms"; fi

echo "-- Freedoom"
if [ ! -d "${SCRIPT_DIR}/freedoom/levels" ]; then
    git clone --depth 1 https://github.com/freedoom/freedoom.git "${SCRIPT_DIR}/freedoom"
fi
echo "   freedoom: $(git -C "${SCRIPT_DIR}/freedoom" log -1 --format='%h %cs' 2>/dev/null || echo present)"

cat > "${SCRIPT_DIR}/config.mk" << EOF
# Generated by setup.sh on $(date)
LWASM = ${LWASM_PATH}
PYTHON = $(command -v python3)
MAME = $(command -v mame || echo mame)
EOF

python3 "${SCRIPT_DIR}/scripts/wad.py" selftest || echo "   wad self-test failed (see above)"

echo
echo "Next:  ./build.sh"
