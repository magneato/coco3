#!/bin/bash
# ==============================================================================
# setup.sh - CoCo3 Wolfenstein 3D development environment (Ubuntu 24.04)
# ==============================================================================
# "Constraints breed elegance, not limitations." - Nom Nom Philosophy
#
# Installs / checks:
#   lwtools   6809 cross-assembler (lwasm).  Built into ./tools if not already installed;
#             an lwtools-4.23.tar.gz in ./tools is used if present (no download needed).
#   mame      the emulator (machine "coco3", needs the coco3 + disk11 ROMs in ~/mame/roms)
#   python3 + numpy + Pillow   used by scripts/wolfai.py and scripts/gen_assets.py
# ==============================================================================
set -e
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOLS_DIR="${SCRIPT_DIR}/tools"
LWTOOLS_VERSION="4.23"

echo "== CoCo3 Wolfenstein 3D - environment setup =="

echo "-- system packages (build tools, mame, python)"
if command -v apt-get &> /dev/null; then
    sudo apt-get update
    sudo apt-get install -y build-essential git wget curl mame python3 python3-numpy python3-pil \
        || echo "   some packages failed - continuing"
else
    echo "   apt-get not found: install build-essential, mame, python3, python3-numpy, python3-pil yourself"
fi

echo "-- lwasm"
LWASM_PATH=""
if command -v lwasm &> /dev/null; then
    LWASM_PATH="$(command -v lwasm)"
elif [ -x "${TOOLS_DIR}/lwtools-${LWTOOLS_VERSION}/lwasm/lwasm" ]; then
    LWASM_PATH="${TOOLS_DIR}/lwtools-${LWTOOLS_VERSION}/lwasm/lwasm"
else
    mkdir -p "${TOOLS_DIR}"
    cd "${TOOLS_DIR}"
    if [ ! -f "lwtools-${LWTOOLS_VERSION}.tar.gz" ]; then
        wget -q "http://www.lwtools.ca/releases/lwtools/lwtools-${LWTOOLS_VERSION}.tar.gz" \
          || wget -q "https://github.com/lwtools/lwtools/archive/refs/tags/v${LWTOOLS_VERSION}.tar.gz" -O "lwtools-${LWTOOLS_VERSION}.tar.gz" \
          || { echo "could not download lwtools; place lwtools-${LWTOOLS_VERSION}.tar.gz in ${TOOLS_DIR} and re-run"; exit 1; }
    fi
    tar xzf "lwtools-${LWTOOLS_VERSION}.tar.gz"
    (cd "lwtools-${LWTOOLS_VERSION}" && make -j"$(nproc)")
    LWASM_PATH="${TOOLS_DIR}/lwtools-${LWTOOLS_VERSION}/lwasm/lwasm"
    cd "${SCRIPT_DIR}"
fi
echo "   lwasm: ${LWASM_PATH}"

echo "-- MAME ROMs"
for r in coco3.zip; do
    if [ -f "${HOME}/mame/roms/${r}" ] || [ -f "/usr/share/games/mame/roms/${r}" ]; then echo "   found ${r}"
    else echo "   MISSING ${r} - put the coco3 ROM set (coco3.rom, disk11.rom) in ~/mame/roms"; fi
done

echo "-- game data"
[ -f "${SCRIPT_DIR}/WOLF3D/VSWAP.WL6" ] && echo "   WOLF3D/ data files present" \
  || echo "   MISSING WOLF3D/*.WL6 + WOLF3D.EXE (Wolfenstein 3D v1.4 registered data): copy them into ${SCRIPT_DIR}/WOLF3D"

cat > "${SCRIPT_DIR}/config.mk" << EOF
# Auto-generated by setup.sh
LWASM = ${LWASM_PATH}
EOF

python3 "${SCRIPT_DIR}/scripts/wolfai.py" selftest || echo "   wolfai self-test failed (see above)"

echo
echo "Next:  ./build.sh   then   ./run.sh"
